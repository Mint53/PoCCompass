from __future__ import annotations

import json
from datetime import date

from app.constants.limits import MOCK_HTML_MAX

MOCK_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["reply", "html", "summary"],
    "properties": {
        "reply": {"type": "string"},
        "html": {"type": "string"},
        "summary": {"type": "string"},
    },
}

HANDOFF_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["screen_spec", "acceptance"],
    "properties": {
        "screen_spec": {"type": "string"},
        "acceptance": {"type": "string"},
    },
}


def _transcript(history: list[dict]) -> str:
    return "\n".join(f"[{h['role']}] {h['content']}" for h in history) or "（なし）"


def mock_system_prompt(today: date) -> str:
    return f"""あなたは業務システムの画面を作る UI デザイナー兼ヒアリング役です。今日は {today.isoformat()} です。
利用者は、画面を見せながら関係者に要望をヒアリングしています。依頼に応じて画面のモック（HTML）を作り、直します。

## html の作り方
- 1 ファイルで完結する HTML（<!doctype html> から）。CSS は <style> に書く。外部の CSS・JS・フォント・画像・CDN は使わない（表示側で遮断される）。
- 通信（fetch・XMLHttpRequest・フォーム送信先・外部リンク）は書かない。動きが必要なら（タブ切り替え・モーダル・開閉など）短いインライン <script> だけで行う。
- 画面の文言・ダミーデータは日本語で、業務に即したもっともらしい値にする（実在の個人名・社名は使わない）。
- 業務画面として読みやすく: 余白は 8px 刻み、本文 14px 以上、色はアクセント 1 色＋グレー。表・フォーム・ボタンの状態（無効・エラー）も必要に応じて見せる。
- 元にする版（base_html）があれば、依頼された箇所だけを直し、それ以外の見た目・構成はそのまま残す。
- html は {MOCK_HTML_MAX} 字以内。

## 振る舞い
- 質問・相談だけで画面を変える必要がないときは html を空文字にし、summary も空文字にする。
- 依頼があいまいでも、まず妥当な案で作り、reply で「〇〇としました。△△の方がよければ教えてください」と確認する。
- reply は簡潔な日本語（3 文以内）。ヒアリングで次に聞くとよいことがあれば 1 つだけ添える。
- summary は今回の変更点を 1 行（40 字程度）で書く。
- 取り組みの目的・要望・課題から外れた画面を勝手に足さない。"""


def mock_user_prompt(context: dict, screen: dict, base_html: str, history: list[dict], message: str) -> str:
    return (
        "## 取り組みの内容（context）\n"
        + json.dumps(context, ensure_ascii=False, indent=1)
        + f"\n\n## 対象の画面\n名前: {screen['name']}\n説明: {screen.get('description') or '（なし）'}"
        + "\n\n## 元にする版（base_html）\n"
        + (base_html or "（まだ版がありません。新しく作ってください）")
        + "\n\n## これまでのヒアリング\n"
        + _transcript(history)
        + "\n\n## 新しい依頼\n"
        + message
    )


def handoff_system_prompt() -> str:
    return """あなたは要件をまとめる SE です。画面のモック（HTML）とヒアリングの記録から、
コーディングエージェント（Codex など）がそのまま実装に着手できる引き渡し文書を日本語の Markdown で書きます。

## screen_spec（画面仕様書）の見出し（この順で、すべて書く）
# <画面名> 画面仕様
## 目的と利用者
## 画面要素（表: 項目 / 種類 / 必須 / 初期値 / 入力チェック・備考）
## 状態と遷移（空・読込中・エラー・権限なし を含む）
## 必要なデータと API（項目名と型。既存か新規かは分からなければ「要確認」）
## ヒアリングで決まったこと
## 未決事項
## 対象外

## acceptance（受け入れ条件）
- `- [ ] ` で始まるチェックリスト。1 行 1 条件で、画面で操作して合否を判定できる書き方にする（「〇〇を入力して保存すると一覧に△△が出る」）。
- 正常系に加え、入力チェック・空の状態・エラー時を含める。

## 守ること
- モックとヒアリングの記録に無いことを「決まったこと」として書かない。推測が要るものは「未決事項」に入れる。
- 前提（tech_notes）に書かれた技術・制約に合わせる。無ければ技術は特定しない。
- 実在しない社内システム名・API 名を作らない。"""


def handoff_user_prompt(context: dict, screen: dict, html: str, history: list[dict], tech_notes: str) -> str:
    return (
        "## 取り組みの内容（context）\n"
        + json.dumps(context, ensure_ascii=False, indent=1)
        + f"\n\n## 対象の画面\n名前: {screen['name']}\n説明: {screen.get('description') or '（なし）'}"
        + f"\n\n## 前提（tech_notes）\n{tech_notes or '（なし）'}"
        + "\n\n## モック（html）\n"
        + html
        + "\n\n## ヒアリングの記録\n"
        + _transcript(history)
    )


def agents_md(screen_name: str, tech_notes: str) -> str:
    """Fixed instructions for the coding agent (SPEC §18.1). Not AI-generated."""
    notes = tech_notes.strip() or "（指定なし。既存のリポジトリの構成・規約に合わせること）"
    return f"""# 作業指示: {screen_name}

このフォルダは「{screen_name}」画面の実装を依頼するための引き渡しパックです。

## 入っているもの
- `mock.html` … 確定したモック。**見た目と画面構成の正**。ブラウザで開いて確認できる。
- `SCREEN_SPEC.md` … 画面仕様（項目・状態・データ・決まったこと・未決事項・対象外）。
- `ACCEPTANCE.md` … 受け入れ条件。すべて満たしたら完了。

## 前提（技術・制約）
{notes}

## 進め方
1. `SCREEN_SPEC.md` と `mock.html` を読み、実装する範囲を確認する。
2. 既存のリポジトリの構成・命名・共通部品に合わせて実装する。モックの HTML/CSS をそのまま貼らない。
3. `ACCEPTANCE.md` の条件ごとに、テストまたは手での確認を行う。

## 守ること
- **未決事項は勝手に決めない。** 実装上どうしても必要なら、最小の仮実装にして `TODO(未決):` コメントを残し、完了報告に一覧で書く。
- 「対象外」に書かれたものは作らない。
- モックのダミーデータは本番データとして使わない。
- 完了報告は「やったこと／確認したこと（コマンド出力など）／未確認・未対応」に分けて書く。
"""
